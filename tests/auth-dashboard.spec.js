import { expect, test } from '@playwright/test'

async function readyScreenshot(page, testInfo, name) {
  await page.evaluate(() => document.fonts.ready)
  await page.evaluate(() => Promise.all([...document.images].map(img => img.decode())))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath(`${name}.png`), fullPage: true })
}

test('login rejects unsupported authentication and has no dashboard preview link', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/login')
  await expect(page.getByRole('heading', { name: '환영합니다' })).toBeVisible()
  await readyScreenshot(page, testInfo, 'login')
  await page.getByRole('button', { name: '로그인 하기', exact: true }).click()
  await expect(page.getByText('아이디를 입력해주세요.', { exact: true })).toBeVisible()
  await page.getByLabel('아이디', { exact: true }).fill('demo-user')
  await page.getByLabel('비밀번호', { exact: true }).fill('not-a-real-secret')
  await page.getByRole('button', { name: '로그인 하기', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('로그인할 수 없습니다')
  await expect(page).toHaveURL('/login')
  await expect(page.getByRole('button', { name: 'Google로 계속하기' })).toHaveCount(0)
  await expect(page.getByRole('link', { name: '대시보드 미리보기' })).toHaveCount(0)
  await page.goto('/dashboard')
  await expect(page).toHaveURL('/dashboard')
  await expect(page.getByRole('heading', { name: /작은 배움으로 오늘의 목표/ })).toBeVisible()
  await expect(page.locator('.app-header .brand-logo')).toHaveAttribute('href', '/dashboard')
  await page.getByRole('button', { name: '메뉴 열기', exact: true }).click()
  await page.getByRole('dialog').getByRole('link', { name: '자료실', exact: true }).click()
  await page.locator('.app-header .brand-logo').click()
  await expect(page).toHaveURL('/dashboard')
  expect(await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))).not.toContain('not-a-real-secret')
  expect(errors).toEqual([])
})

test('signup validates fields, preserves back navigation and completes only a demo', async ({ page }, testInfo) => {
  await page.goto('/signup')
  await readyScreenshot(page, testInfo, 'signup-details')
  await page.getByRole('button', { name: '다음: 학습 성향 선택' }).click()
  await expect(page.getByText('닉네임을 입력해주세요.', { exact: true })).toBeVisible()
  await page.getByLabel('닉네임', { exact: true }).fill('배움이')
  await page.getByLabel('비밀번호', { exact: true }).fill('demo-only-password')
  await page.getByLabel('비밀번호 확인', { exact: true }).fill('different')
  await page.getByLabel('소속 학교', { exact: true }).fill('모람대학교')
  await page.getByLabel('학과', { exact: true }).fill('컴퓨터공학과')
  await page.getByRole('button', { name: '중복확인', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('닉네임을 확인할 수 없습니다')
  await page.getByRole('button', { name: '다음: 학습 성향 선택' }).click()
  await expect(page.getByText('비밀번호가 일치하지 않습니다.', { exact: true })).toBeVisible()
  await page.getByLabel('비밀번호 확인', { exact: true }).fill('demo-only-password')
  await page.getByRole('button', { name: '다음: 학습 성향 선택' }).click()
  await page.getByRole('radio', { name: /꾸준형/ }).check()
  await page.getByRole('radio', { name: /이해형/ }).check()
  await readyScreenshot(page, testInfo, 'signup-preferences')
  await page.getByRole('button', { name: '이전', exact: true }).click()
  await expect(page.getByLabel('닉네임', { exact: true })).toHaveValue('배움이')
  await page.getByRole('button', { name: '다음: 학습 성향 선택' }).click()
  await expect(page.getByRole('radio', { name: /꾸준형/ })).toBeChecked()
  await page.getByRole('button', { name: '입력 완료', exact: true }).click()
  await expect(page.getByRole('heading', { name: '입력 완료', exact: true })).toBeVisible()
  await expect(page.getByText('실제 계정은 생성되지 않았습니다.')).toHaveCount(0)
  await expect(page.getByRole('textbox')).toHaveCount(0)
  expect(await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))).not.toContain('demo-only-password')
  await readyScreenshot(page, testInfo, 'signup-complete')
})

test('dashboard demo filters, cancels a lesson and adds a local schedule', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/dashboard')
  await readyScreenshot(page, testInfo, 'dashboard')
  await expect(page.locator('.todo-card')).toHaveCount(4)
  const search = page.getByRole('textbox', { name: '대시보드 과목 검색' })
  if (!await search.isVisible()) await page.getByRole('button', { name: '검색 열기' }).click()
  await search.fill('세계와 시민')
  await expect(page.locator('.todo-card')).toHaveCount(1)
  await search.fill('없는과목')
  await expect(page.getByText('검색한 과목이 없습니다.', { exact: true })).toBeVisible()
  await search.fill('')
  await page.getByRole('button', { name: '주제 연구 휴강 처리', exact: true }).click()
  await expect(page.getByRole('button', { name: '주제 연구 휴강 해제', exact: true })).toBeVisible()
  const timetableView = page.getByRole('button', { name: '주간 시간표', exact: true })
  if (await timetableView.isVisible()) await timetableView.click()
  await page.getByRole('button', { name: '새 과목 추가', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('시간표 이름', { exact: true }).fill('프론트엔드 스터디')
  await dialog.getByRole('radio', { name: '하늘', exact: true }).check()
  await dialog.getByRole('combobox', { name: '시작 시간', exact: true }).selectOption('13')
  await dialog.getByRole('combobox', { name: '종료 시간', exact: true }).selectOption('12')
  await dialog.getByRole('button', { name: '추가하기', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('종료 시간은 시작 시간보다 늦어야')
  await dialog.getByRole('combobox', { name: '종료 시간', exact: true }).selectOption('14')
  await dialog.getByRole('button', { name: '추가하기', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: /프론트엔드 스터디,/ }).click()
  await expect(page.getByRole('dialog').getByRole('heading', { name: '프론트엔드 스터디' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const overviewView = page.getByRole('button', { name: '오늘의 학습', exact: true })
  if (await overviewView.isVisible()) await overviewView.click()
  await page.getByRole('link', { name: '퀴즈하기', exact: true }).click()
  await expect(page).toHaveURL('/study/setup')
  expect(errors).toEqual([])
})
