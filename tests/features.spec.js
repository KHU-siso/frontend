test('head, face and outfit layers coexist without replacing the original body', async ({ page }, info) => {
  await page.addInitScript(key => {
    if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ version: 1, userId: 'local-demo-user', coinBalance: 100, ownedItemIds: [], equippedItems: {}, rewardHistory: {} }))
  }, economyKey)
  await page.goto('/shop')
  const originalBody = await page.locator('.ong-avatar__body').getAttribute('src')
  for (const id of ['bear-hood', 'round-glasses', 'classic-buttons']) {
    await page.locator(`.wardrobe-item[data-product-id="${id}"]`).click()
    await page.getByRole('button', { name: '구매하기', exact: true }).click()
  }
  await page.getByRole('link', { name: /^내 보관함 \(/ }).click()
  for (const id of ['bear-hood', 'round-glasses', 'classic-buttons']) {
    await page.locator(`.wardrobe-item[data-product-id="${id}"]`).click()
    await page.getByRole('button', { name: '착용하기', exact: true }).click()
  }
  await expect(page.locator('.ong-avatar__wearable')).toHaveCount(3)
  await expect(page.locator('.ong-avatar__body')).toHaveAttribute('src', originalBody)
  await page.reload()
  await expect(page.locator('.ong-avatar__wearable')).toHaveCount(3)
  await expect(page.locator('.ong-avatar__body')).toHaveAttribute('src', originalBody)
  await screenshot(page, info, 'inventory-multiple-slots')
})
