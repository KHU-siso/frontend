test('quiz feedback, result and one-time persisted coin reward', async ({ page }, info) => {
  await startQuiz(page, { count: 2 })
  await page.getByRole('radio', { name: /1592/ }).check()
  await page.getByRole('button', { name: '정답 확인', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('정답이에요!')
  await expect(page.locator('.study-header__progress > span')).toHaveText('1/2')
  await screenshot(page, info, 'quiz-correct')
  await page.getByRole('button', { name: '다음 문제로 넘어가기', exact: true }).click()
  await page.getByRole('radio', { name: /신분제/ }).check()
  await page.getByRole('button', { name: '정답 확인', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('아쉬워요')
  await page.getByRole('button', { name: '결과 확인', exact: true }).click()
  await expect(page.locator('.result-ring')).toHaveText('50%')
  await screenshot(page, info, 'quiz-result')
  await page.getByRole('link', { name: '코인 보상 확인', exact: true }).click()
  await expect(page.getByTestId('coin-balance')).toHaveText('15 COIN')
  await page.getByRole('button', { name: '코인 받기', exact: true }).click()
  await expect(page.getByTestId('coin-balance')).toHaveText('16 COIN')
  await expect(page.getByRole('status')).toContainText('보상 지급 완료')
  await expect(page.getByRole('button', { name: '코인 받기', exact: true })).toHaveCount(0)
  await expect(page.getByRole('link', { name: '다음 문제풀기', exact: true })).toBeVisible()
  await page.goBack()
  await page.getByRole('link', { name: '코인 보상 확인', exact: true }).click()
  await expect(page.getByTestId('coin-balance')).toHaveText('16 COIN')
  await expect(page.getByRole('status')).toContainText('보상 지급 완료')
  await expect(page.getByRole('button', { name: '코인 받기', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading', { name: '보상받을 완료 학습이 없습니다' })).toBeVisible()
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).coinBalance, economyKey)).toBe(16)
})

