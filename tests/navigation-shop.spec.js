import { expect, test } from '@playwright/test'

const economyKey = 'moram.demo.local-user.economy.v1'
const product = (page, id) => page.locator(`.wardrobe-item[data-product-id="${id}"]`)
async function ready(page) {
  await page.evaluate(() => document.fonts.ready)
  await page.evaluate(() => Promise.all([...document.images].map(img => img.decode())))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}

test('Figma navigation keeps the header clear, highlights routes, closes and links to chat', async ({ page }, info) => {
  await page.goto('/dashboard')
  await ready(page)
  const header = await page.locator('.app-header').boundingBox()
  await page.getByRole('button', { name: '메뉴 열기', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'MORAM 메뉴' })
  await expect(dialog).toBeVisible()
  expect((await dialog.boundingBox()).y).toBeCloseTo(header.y + header.height, 0)
  await expect(dialog).toHaveCSS('backdrop-filter', 'blur(3px)')
  await expect(dialog.getByRole('link', { name: '홈', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(dialog.getByRole('link', { name: '아이템 보관함', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('link', { name: '코인샵', exact: true })).toHaveCount(1)
  await expect(dialog.locator('.navigation-icon')).toHaveCount(9)
  await ready(page)
  await page.screenshot({ path: info.outputPath('figma-navigation.png') })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: '메뉴 열기', exact: true })).toBeFocused()
  await page.getByRole('button', { name: '메뉴 열기', exact: true }).click()
  await dialog.getByRole('link', { name: '자료실', exact: true }).click()
  await expect(page).toHaveURL('/materials')
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: '메뉴 열기', exact: true }).click()
  await expect(dialog.getByRole('link', { name: '자료실', exact: true })).toHaveAttribute('aria-current', 'page')
  await dialog.getByRole('button', { name: '닫기', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: '메뉴 열기', exact: true }).click()
  const panel = await dialog.locator('.moram-modal__content').boundingBox()
  await page.mouse.click(panel.x + panel.width + 15, panel.y + 50)
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: '메뉴 열기', exact: true }).click()
  await dialog.getByRole('link', { name: 'AI 채팅', exact: true }).click()
  await expect(page).toHaveURL('/chat')
  await expect(page.getByRole('textbox', { name: '메시지', exact: true })).toBeVisible()
})

test('material chevrons stay centered and expand without relying on font glyphs', async ({ page }, info) => {
  await page.goto('/materials')
  await ready(page)
  const toggle = page.locator('.material-course__toggle').first()
  const icon = toggle.locator('svg')
  const text = toggle.locator(':scope > span')
  const iconBox = await icon.boundingBox()
  const textBox = await text.boundingBox()
  expect(Math.abs(iconBox.y + iconBox.height / 2 - textBox.y - textBox.height / 2)).toBeLessThanOrEqual(1)
  expect(iconBox.x + iconBox.width).toBeLessThan(textBox.x)
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(page.locator('.material-course__details').first()).toBeVisible()
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await page.screenshot({ path: info.outputPath('materials-chevron.png'), fullPage: true })
})

test('unified shop tabs preserve purchases and equipment without reloads or storage reset', async ({ page }, info) => {
  await page.goto('/shop')
  await expect(page.locator('.wardrobe-item')).toHaveCount(86)
  await expect(page.getByRole('link', { name: '상점', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.evaluate(() => { window.shopNavigationSentinel = 'kept' })
  await product(page, 'cream-scarf').click()
  await page.getByRole('button', { name: '구매하기', exact: true }).click()
  await expect(page.getByTestId('coin-balance')).toHaveText('9 COIN')
  await page.getByRole('link', { name: /^내 보관함 \(/ }).click()
  await expect(page).toHaveURL('/shop?tab=inventory')
  expect(await page.evaluate(() => window.shopNavigationSentinel)).toBe('kept')
  await expect(page.locator('.wardrobe-item')).toHaveCount(2)
  await product(page, 'cream-scarf').click()
  await page.getByRole('button', { name: '착용하기', exact: true }).click()
  await ready(page)
  await page.screenshot({ path: info.outputPath('unified-inventory.png'), fullPage: true })
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), economyKey)
  await page.goto('/inventory')
  await expect(page).toHaveURL('/shop?tab=inventory')
  await expect(page.getByRole('link', { name: /^내 보관함 \(/ })).toHaveAttribute('aria-current', 'page')
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)), economyKey)).toEqual(saved)
  await page.reload()
  await expect(page.locator('.ong-avatar [data-item-id="cream-scarf"]')).toHaveCount(1)
  await expect(page.getByTestId('coin-balance')).toHaveText('9 COIN')
  await page.getByRole('button', { name: '메뉴 열기', exact: true }).click()
  await page.getByRole('dialog').getByRole('link', { name: '홈', exact: true }).click()
  await expect(page.locator('.ong-avatar [data-item-id="cream-scarf"]')).toHaveCount(1)
  await page.getByRole('link', { name: '아이템 보관함으로 이동', exact: true }).click()
  await expect(page).toHaveURL('/shop?tab=inventory')
  await page.getByRole('link', { name: '상점', exact: true }).click()
  await expect(page).toHaveURL('/shop')
  await expect(page.locator('.wardrobe-item')).toHaveCount(86)
})
