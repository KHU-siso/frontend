import { expect, test } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

const subjectKey = 'moram.subjects.v1'
const economyKey = 'moram.demo.local-user.economy.v1'
test.beforeEach(async ({ page }) => { await page.clock.install({ time: new Date('2026-10-29T12:00:00+09:00') }) })
async function menu(page, label) {
  await page.getByRole('button', { name: '메뉴 열기', exact: true }).click()
  await page.getByRole('dialog').getByRole('link', { name: label, exact: true }).click()
}
async function capture(page, info, name) {
  await page.evaluate(() => document.fonts.ready)
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0) })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await mkdir('artifacts/profile-subjects', { recursive: true })
  await page.screenshot({ path: `artifacts/profile-subjects/${name}-${info.project.name}.png`, fullPage: true })
}

test('profile follows materials additions, subject home links, edits, semester changes and deletion', async ({ page }, info) => {
  test.setTimeout(60000)
  await page.goto('/materials')
  const before = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), subjectKey)
  const economy = await page.evaluate(key => localStorage.getItem(key), economyKey)
  await page.getByRole('button', { name: '＋ 과목 추가', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('과목 이름 (필수)', { exact: true }).fill('과목 연동 확인')
  await dialog.getByLabel('교수 이름 (필수)', { exact: true }).fill('연동 교수')
  await dialog.getByLabel('학기 (필수)', { exact: true }).selectOption('2026-2')
  await dialog.getByRole('button', { name: '과목 등록', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const id = await page.evaluate(key => JSON.parse(localStorage.getItem(key)).subjects.find(s => s.name === '과목 연동 확인').id, subjectKey)
  await menu(page, '마이페이지')
  await expect(page.getByLabel('학기 선택', { exact: true })).toHaveValue('2026-2')
  await expect(page.locator('.profile-subject-card')).toHaveCount(before.subjects.filter(s => s.semester === '2026-2').length + 1)
  let card = page.locator('.profile-subject-card').filter({ has: page.getByText('과목 연동 확인', { exact: true }) })
  await expect(card).toContainText('2026년 2학기 · 연동 교수')
  await expect(card).toHaveAttribute('href', `/materials/${id}`)
  await capture(page, info, 'populated')
  await card.focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(`/materials/${id}`)
  await expect(page.getByRole('heading', { name: '과목 연동 확인', exact: true })).toBeVisible()
  await menu(page, '자료실')
  await page.getByRole('button', { name: '과목 연동 확인 과목 수정', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('과목 이름 (필수)', { exact: true }).fill('수정된 학습 과목')
  await dialog.getByLabel('교수 이름 (필수)', { exact: true }).fill('변경 교수')
  await dialog.getByLabel('학기 (필수)', { exact: true }).selectOption('2027-1')
  await dialog.getByRole('button', { name: '변경 저장', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await menu(page, '마이페이지')
  await expect(page.getByLabel('학기 선택', { exact: true })).toHaveValue('2027-1')
  card = page.locator('.profile-subject-card').filter({ has: page.getByText('수정된 학습 과목', { exact: true }) })
  await expect(card).toContainText('2027년 1학기 · 변경 교수')
  await expect(card).toHaveAttribute('href', `/materials/${id}`)
  await page.reload()
  await expect(page.getByLabel('학기 선택', { exact: true })).toHaveValue('2027-1')
  await expect(card).toBeVisible()
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), subjectKey)
  for (const field of ['notes', 'exams', 'assignments', 'drafts', 'attendance', 'calendarEvents']) expect(saved[field]).toEqual(before[field])
  await page.getByLabel('학기 선택', { exact: true }).selectOption('2026-2')
  await expect(card).toHaveCount(0)
  await menu(page, '자료실')
  await expect(page.getByLabel('학기 선택', { exact: true })).toHaveValue('2026-2')
  await page.getByLabel('학기 선택', { exact: true }).selectOption('2027-1')
  await page.getByRole('button', { name: '수정된 학습 과목 과목 삭제', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '삭제하기', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await menu(page, '마이페이지')
  await expect(page.locator('.profile-subject-card')).toHaveCount(0)
  await expect(page.getByText('등록된 과목이 없습니다', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: '과목 추가하기', exact: true })).toHaveAttribute('href', '/materials')
  await capture(page, info, 'empty')
  const after = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), subjectKey)
  expect(after.subjects.some(s => s.id === id)).toBe(false)
  expect(after.subjects).toEqual(before.subjects)
  for (const field of ['notes', 'exams', 'assignments', 'drafts', 'attendance', 'calendarEvents']) expect(after[field]).toEqual(before[field])
  expect(await page.evaluate(key => localStorage.getItem(key), economyKey)).toBe(economy)
})

test('empty current semester, long subject cards and Home navigation remain usable', async ({ page }, info) => {
  await page.addInitScript(key => {
    const stamp = '2026-10-29T03:00:00.000Z'
    localStorage.setItem(key, JSON.stringify({ version: 1, subjects: [
      { id: 'prior-a', name: '긴 과목 이름과 담당 교수 정보가 있어도 줄바꿈되는 학습 과목', teacher: '이름이 긴 담당 교수', semester: '2026-1', sessionsPerWeek: 2, source: 'user', createdAt: stamp, updatedAt: stamp },
      { id: 'prior-b', name: '이전 학기 과목', teacher: '이전 담당 교수', semester: '2026-1', sessionsPerWeek: 1, source: 'user', createdAt: stamp, updatedAt: stamp },
    ], notes: [], exams: [], assignments: [], calendarEvents: [], pendingFileDeletions: [], drafts: {}, attendance: {} }))
  }, subjectKey)
  await page.goto('/mypage')
  await expect(page.getByText('등록된 과목이 없습니다', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '과목 추가하기', exact: true }).click()
  await expect(page).toHaveURL('/materials')
  await expect(page.getByRole('button', { name: '＋ 과목 추가', exact: true })).toBeVisible()
  await page.getByLabel('학기 선택', { exact: true }).selectOption('2026-1')
  await menu(page, '마이페이지')
  await expect(page.locator('.profile-subject-card')).toHaveCount(2)
  await expect(page.locator('.profile-subject-card').first()).toContainText('이름이 긴 담당 교수')
  await capture(page, info, 'long-cards')
  await page.getByRole('button', { name: '메뉴 열기', exact: true }).click()
  const home = page.getByRole('dialog').getByRole('link', { name: '홈', exact: true })
  await expect(home).toHaveAttribute('href', '/dashboard')
  await home.click()
  await expect(page).toHaveURL('/dashboard')
})
