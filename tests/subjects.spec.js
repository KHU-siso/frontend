    const downloaded = page.waitForEvent('download')
    await page.getByRole('button', { name: `예시.${extension} 다운로드`, exact: true }).click()
    expect(await readFile(await (await downloaded).path(), 'utf8')).toBe(`bytes-${extension}`)
